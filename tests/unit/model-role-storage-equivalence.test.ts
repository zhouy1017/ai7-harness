// The M1 snapshots record the inheritance path before channels supplied a default to underlying Flash.
beforeEach(() => { vi.spyOn(modelService, 'modelServiceRecommendedModels').mockReturnValue(undefined); });
afterEach(() => vi.restoreAllMocks());

function withUntestedConnectionHistory(m1: unknown): unknown {
  return JSON.parse(JSON.stringify(m1), (_key, value) => value && typeof value === 'object' && value.connectionTest === null
    ? { ...value, connectionTests: [] } : value);
}

// Generated by the capture script at 57c501177; the full regeneration script is retained in the slice PR for #1650.
it.each(['requests', 'revision-116 mapping'])('keeps M1 answers through %s (#1650)', async mode => {
  vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-11-21T00:00:00Z'));
  const answers: Record<string, unknown> = {};
  for (const name of Object.keys(expected) as Array<keyof typeof expected>) {
    const roots = await createServiceTestRoots('ai7-m1-capture-');
    let store = await EditorialStore.open(roots.dataRoot, roots.codeRoot);
    try {
      const pro = store.saveModelServiceConnection('Synthetic Claude', '00000000-0000-4000-8000-000000001650', 'ready', 'anthropic-claude');
      store.selectMainRoleModel('anthropic-claude', 'claude-opus-5', 'high');
      const go = store.saveModelServiceConnection('Synthetic Go', '00000000-0000-4000-8000-000000001651', 'ready', 'opencode-go');
      if (name === 'same-channel') store.selectFastRoleModel('anthropic-claude', 'claude-haiku-4-5', 'low');
      if (['two-channels', 'cleared', 'missing-flash', 'refused-flash', 'task-flash', 'task-other'].includes(name)) store.selectFastRoleModel('opencode-go', 'glm-5.3-flash', 'low');
      if (name === 'cleared') store.clearFlashModel();
      if (name === 'missing-flash') store.setModelServiceCredentialState(go.credentialReference, 'missing');
      store.close();
      const db = new DatabaseSync(join(roots.dataRoot, 'store', 'ai7.sqlite'));
      if (name === 'refused-flash') { db.prepare('UPDATE model_service_connections SET fast_model_id = ? WHERE connection_id = ?').run('gpt-5.6-luna', go.connectionId); writeModelRoleChoice(db, 'foreground-flash', { connectionId: go.connectionId, modelId: 'gpt-5.6-luna', reasoningEffort: 'low' }); }
      if (name === 'refused-pro') { db.prepare('UPDATE model_service_connections SET model_id = ? WHERE connection_id = ?').run('gpt-5.6-luna', go.connectionId); writeModelRoleChoice(db, 'foreground-pro', { connectionId: go.connectionId, modelId: 'gpt-5.6-luna' }); }
      if (name === 'go-fallback') writeModelRoleChoice(db, 'foreground-pro', null);
      const rows = expected[name].rows;
      if (mode === 'revision-116 mapping') {
        db.exec('DELETE FROM model_role_choices');
        for (const choice of mapRevision116ModelRoleChoices(rows)) writeModelRoleChoice(db, choice.roleId, choice);
      }
      db.close(); store = await EditorialStore.open(roots.dataRoot, roots.codeRoot);
      const connections = store.getModelServiceConnections(), modelRoles = store.getModelRoles();
      const state: ModelServiceStoredStateProjection = { proxy: { mode: 'direct' }, connection: null, connections, channels: [], modelRoles, launchPolicy: {} as ModelServiceStoredStateProjection['launchPolicy'] };
      const settings = modelServiceSettingsProjection(state, connections, store.getSearchBackendSettings(), true, 'win32');
      const override = name === 'task-flash' ? { modelConnectionId: go.connectionId } : name === 'task-other' ? { modelConnectionId: pro.connectionId } : {};
      const bindings = Object.fromEntries([...MODEL_ROLE_IDS, 'main-editorial', 'fast-interaction'].map(role => {
        const binding = store.getConfiguredModelRoleBinding(role as (typeof MODEL_ROLE_IDS)[number], override);
        return [role, { binding, digest: sha256Hex(JSON.stringify(binding)) }];
      }));
      answers[name] = { rows, modelRoles, connections, cards: settings.roles, settingsModelRoles: JSON.stringify(settings.modelRoles), bindings };
    } finally { store.close(); await roots.dispose(); }
  }
  vi.useRealTimers();
  expect(answers).toEqual(withUntestedConnectionHistory(expected));
});

it('keeps M1 answers through route, credential, selection and effort sequences (#1650)', async () => {
  expect(await captureModelRoleSequences()).toEqual(withUntestedConnectionHistory(sequenceAnswers));
});
